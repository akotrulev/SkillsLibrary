def about(audience="shareable", identifier="**Id:** AREA-001\n", sha="abc1234", extra=""):
    return (
        f"{identifier}**Created:** 2026-08-02\n**Owned by:** `x`\n**Derived from:** code @ `{sha}` on 2026-08-02\n"
        f"**Audience:** {audience}\n{extra}"
    )


FEATURE_ABOUT = "**Created:** 2026-08-02\n**Generated by** feature-documenter @ `abc1234` on 2026-08-02\n**Audience:** shareable\n"


def guide(body="Members book sessions.", flow=TASK, sections=None, questions=QUESTIONS, about_text=None, top=""):
    parts = {
        "Who uses it": "| Who | What they do here |\n|---|---|\n| Members | Book |",
        "For members": flow,
        **(sections or {}),
        "Open questions": questions,
        "About this document": about() if about_text is None else about_text,
    }
    text = "\n\n".join(f"## {heading}\n\n{content}" for heading, content in parts.items())
    return f"# Area\n\n{top}{body}\n\n{text}\n"


def overview(journey="A shop.", flows="### First order\n\n1. Signs up.\n2. Orders.", first="Who uses it"):
    parts = {
        first: "| Who | What they do | Start here |\n|---|---|---|\n| Shoppers | Order | [Orders](areas/orders.md) |",
        "The journey": journey,
        "Areas, by who uses them": "### For shoppers\n\nOrders.",
        "End-to-end flows": flows,
        "What is not documented": "Nothing.",
        "About this document": about(identifier=""),
    }
    text = "\n\n".join(f"## {heading}\n\n{content}" for heading, content in parts.items())
    return f"# System\n\nA shop for makers.\n\n{text}\n"


def screen_task(name="Set up plans", target="screenshots/plans.png", alt="The Plans screen with the Basic plan"):
    return f"### {name}\n\n**Where:** **Plans**\n\n![{alt}]({target})\n\n1. Open **Plans**.\n2. Save the plan."


def staff(flow):
    return {"For staff": flow}


def limited_task(steps=1, outcomes=1, alerts=0):
    lines = ["### Book a session", ""] + [f"{i}. Step." for i in range(1, steps + 1)]
    lines += ["", "**What happens next**", ""] + [f"- Outcome {i}." for i in range(1, outcomes + 1)]
    lines += [f"\n> [!NOTE]\n> Alert {i}." for i in range(1, alerts + 1)]
    return "\n".join(lines)


def key_ideas(count):
    return "\n".join(f"- **Term{chr(97 + i)}** — one line" for i in range(count))


def good_to_know(count):
    return "\n\n".join(f"### Question {chr(97 + i)}?\n\nYes." for i in range(count))


def words(count):
    return " ".join(["word"] * count)


def prose(count):
    return " ".join(["Word."] * count)


def sentence(count):
    return "Word " + " ".join(["word"] * (count - 1)) + "."


def without_section(text, title):
    return re.sub(rf"## {re.escape(title)}\n\n.*?(?=\n## |\Z)", "", text, flags=re.DOTALL)


