def limited_task(steps=1, outcomes=1, alerts=0):
    lines = ["### Book a session", ""] + [f"{i}. Step." for i in range(1, steps + 1)]
    lines += ["", "**What happens next**", ""] + [f"- Outcome {i}." for i in range(1, outcomes + 1)]
    lines += [f"\n> [!NOTE]\n> Alert {i}." for i in range(1, alerts + 1)]
    return "\n".join(lines)


def key_ideas(count):
    return "\n".join(f"- **Term{chr(97 + i)}** — one line" for i in range(count))


def good_to_know(count):
    return "\n\n".join(f"### Question {chr(97 + i)}?\n\nYes." for i in range(count))


def words(count):
    return " ".join(["word"] * count)


def prose(count):
    return " ".join(["Word."] * count)


def sentence(count):
    return "Word " + " ".join(["word"] * (count - 1)) + "."


def without_section(text, title):
    return re.sub(rf"## {re.escape(title)}\n\n.*?(?=\n## |\Z)", "", text, flags=re.DOTALL)


