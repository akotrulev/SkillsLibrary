#!/usr/bin/env python3
"""Deterministic lint for a three-level documentation set (guide, behind the scenes, technical).

Usage:
  doc-lint.py --dir <folder>                          lint every set found (any *.behind-the-scenes.md or
                                                      *.technical.md marks one)
  doc-lint.py <guide.md> <behind.md> <technical.md>   lint one explicit set

Output: ERROR|WARN <path>:<line> <rule-id> <message>. Exit 0 when no ERROR, 1 otherwise.
Level 3 may be split into <name>.technical.md plus <name>.technical.<topic>.md siblings; Level 3 sections,
row ids, T ids and Q citations are checked over all of them. A set named system-overview has its own sections.

Rules:
  no-sets          ERROR  --dir does not exist or holds no set
  set-complete     ERROR  a set has <name>.md, <name>.behind-the-scenes.md, <name>.technical.md
  levels-links     ERROR  **Levels:** links Guide, Behind the scenes, Technical reference, each to its own
                          level's file (targets exist in --dir mode)
  header           ERROR  **Created:** and either **Owned by:** + **Derived from:** (area) or **Generated by** (feature);
                          Level 1 reads them from "## About this document" and an area guide opens that section with
                          **Id:** AREA-nnn; Levels 2-3 read them from the top
  audience         ERROR  **Audience:** is shareable (Level 1) / internal (Levels 2-3)
                   WARN   Level 2 marked shareable
  stamp-agree      WARN   a file carries no commit sha, or the three shas differ
  tier-tags        ERROR  #observed / #inferred appear only in Level 3
  confirmed        ERROR  #confirmed in Levels 1-2
                   WARN   #confirmed in Level 3 outside the "How to read this" legend
  code-nouns       ERROR  status codes, HTTP verb + path, source-file names, file:line, inline code in Levels 1-2
                   WARN   code identifiers (PascalCase, lowerCamel, I-prefixed, snake_case) or a bare 4xx/5xx
                          next to a response word in Levels 1-2
                          Inside a ```mermaid fence only the quoted labels and the text after a ":" are read
  jargon           ERROR  technical jargon in Levels 1-2 (Level 2 allows "database"); a mermaid fence as for code-nouns
  defect-words     WARN   bug, defect, flaw, broken, wrong, mistake, faulty, incorrect, vulnerab*, "should have"
                          in Levels 1-2, outside quotes
  guarantee-words  WARN   timing or delivery guarantees in Levels 1-2, outside quotes
  qid-unique       ERROR  Q ids unique across Levels 1-2 open questions; T ids unique in Level 3
  ref-resolves     ERROR  ids cited in the evidence index are Level 3 row ids; Q ids in Level 3 tables exist in
                          Levels 1-2
  index-level      ERROR  every evidence-index Level cell is Guide or Behind the scenes
  index-evidence   ERROR  an #inferred row names a Q or T id; an #observed row has evidence
  index-coverage   ERROR  every flow of Levels 1-2 has an evidence-index row for its heading
  index-steps      WARN   a cited step or outcome number exists in that flow
  sections         ERROR  each level has its required ## headings (Level 1: Who uses it, at least one "For ...",
                          Open questions, About this document); Evidence index is in the main Level 3 file
  internal-ids     ERROR  Level 1: an AREA-/FLOW-/ENT-/DEC-/EVT-/RX-/INV- id outside "## About this document", or a Q<n>
                          outside the first cell of an open-questions row
  alerts           ERROR  Levels 1-2: a "> [!X]" alert whose kind is not NOTE, TIP, IMPORTANT or WARNING
  example          WARN   a Level 1 task with a formula line and no **Example**, in a guide with no "A ... in numbers"
Flows are the ### headings under "## For ..." and "## What happens automatically" (Level 1), "## What happens behind
the scenes" (Level 2) or "## End-to-end flows" (overview). A flow's numbered items are its steps; the bullets under
**What happens next** are its outcomes.
"""
import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

GUIDE, BEHIND, TECH = "Guide", "Behind the scenes", "Technical reference"
LEVEL_SUFFIX = {GUIDE: ".md", BEHIND: ".behind-the-scenes.md", TECH: ".technical.md"}
OVERVIEW_NAME = "system-overview"

REQUIRED_SECTIONS = {
    GUIDE: ["Who uses it", "Open questions", "About this document"],
    BEHIND: [
        "At a glance", "The parts involved", "What happens behind the scenes", "What is remembered, and where",
        "Timing and ordering", "When parts fail or are slow", "If you change this", "Open questions",
    ],
    TECH: [
        "How to read this", "Quick facts", "Code map", "Entry points", "Rules, validations and decisions",
        "Data", "Control flow", "Events and reactions", "Integrations", "Configuration", "Errors",
        "Telemetry", "Tests", "Business ↔ code vocabulary", "Changing this safely", "Findings",
        "Technical open questions", "Evidence index",
    ],
}
OVERVIEW_SECTIONS = {
    GUIDE: ["Overview", "The areas", "End-to-end flows", "What is not documented"],
    BEHIND: ["At a glance", "What runs when", "Where information lives", "How a failure travels", "End-to-end flows"],
    TECH: [
        "How to read this", "Stack and versions", "Module structure", "Foundations", "Coverage ledger",
        "Findings", "Evidence index",
    ],
}
FLOW_PARENT = {BEHIND: "What happens behind the scenes"}
AUTOMATIC_WORK = "What happens automatically"
ABOUT = "About this document"
OVERVIEW_FLOW_PARENT = "End-to-end flows"
EXPECTED_AUDIENCE = {GUIDE: "shareable", BEHIND: "internal", TECH: "internal"}
INDEX_LEVELS = (GUIDE, BEHIND)

JARGON = [
    "endpoint", "payload", "handler", "middleware", "idempotent", "idempotency", "eventual consistency",
    "webhook", "microservice", "API", "JSON", "SQL", "database", "schema", "outbox", "consumer", "cron",
]
LEVEL_JARGON = {GUIDE: JARGON, BEHIND: [w for w in JARGON if w != "database"]}
DEFECT_WORDS = re.compile(
    r"\b(bug(?:s|gy)?|defect\w*|flaw\w*|broken|wrong\w*|mistake\w*|mistaken|faulty|incorrect\w*|vulnerab\w*|"
    r"should have)\b",
    re.IGNORECASE,
)
GUARANTEE_WORDS = re.compile(
    r"\b(exactly once|at most one|at most once|immediately|instantly|as soon as|in real time|right away)\b",
    re.IGNORECASE,
)
QUOTED = re.compile(r"“[^”]*”|\"[^\"]*\"")
IDENT_ALLOW = {
    "PayPal", "GitHub", "JavaScript", "TypeScript", "iOS", "iPhone", "iPad", "macOS",
    "sequenceDiagram", "stateDiagram", "classDiagram", "erDiagram",
}
HEADER_PREFIXES = (
    "**Created", "**Owned by", "**Derived from", "**Generated by", "**Audience",
    "**Levels", "**Models", "**Last updated", "**Commit", "**Id:**",
)
ALERT = re.compile(r"^\s*>\s*\[!(\w+)\]")
ALERT_KINDS = {"NOTE", "TIP", "IMPORTANT", "WARNING"}
INTERNAL_ID = re.compile(r"\b(?:(?:AREA|FLOW|ENT|DEC|EVT|RX|INV)-\d+|Q\d+)\b")
AREA_ID_LINE = re.compile(r"\*\*Id:\*\* AREA-\d+")
FORMULA = re.compile(r"^\s*(?:[-*]\s+|\d+\.\s+)?[A-Z][A-Za-z' ]* = \S")
QUOTED_LABEL = re.compile(r'"[^"]*"')
STATUS_CODE = re.compile(
    r"(?i:\b(HTTP|status)\s+[1-5]\d\d\b)|\b[1-5]\d\d (OK|Created|Accepted|No Content|Bad Request|Unauthorized|"
    r"Forbidden|Not Found|Conflict|Gone|Unprocessable|Too Many Requests|Internal Server Error)\b"
)
HTTP_ROUTE = re.compile(r"\b(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS) /")
RESPONSE_STATUS = re.compile(
    r"\b(?:answers?|answered|returns?|returned|responds?|responded|replies|replied)\s+(?:with\s+)?(?:an?\s+)?"
    r"[45]\d\d\b(?!\s+(?!(?:errors?|responses?|status|code|and|or|when|if|because|to|for)\b)[A-Za-z])"
    r"|\b[45]\d\d\s+(?:errors?|responses?)\b",
    re.IGNORECASE,
)
SOURCE_EXT = re.compile(r"\w\.(cs|ts|tsx|java|py|rs|js|sql|json|ya?ml)\b")
FILE_LINE = re.compile(r"\w\.[A-Za-z]\w*:\d+")
IDENTIFIER = re.compile(r"\b(?:[A-Z][a-z]+[A-Z]\w*|[a-z]+[A-Z]\w*|I[A-Z][a-z]\w*|[a-z][a-z0-9]*(?:_[a-z0-9]+)+)\b")
LINK_TARGET = re.compile(r"\]\([^)]*\)")
SHA = re.compile(r"@\s*`?([0-9a-f]{7,40})`?")
STEP_CITE = re.compile(r"·\s*steps?\s+(\d+)(?:\s*[–-]\s*(\d+))?")
OUTCOME_CITE = re.compile(r"·\s*outcomes?\s+(\d+)(?:\s*[–-]\s*(\d+))?")
CITED_ID = re.compile(r"\*\*([A-Z]+\d+)\*\*|\bsee\s+(?!Q\d)([A-Z]+\d+)\b")
EMPTY_EVIDENCE = ("", "—", "-")


@dataclass(frozen=True)
class Finding:
    severity: str
    path: Path
    line: int
    rule: str
    message: str

    def __str__(self):
        return f"{self.severity} {self.path}:{self.line} {self.rule} {self.message}"


@dataclass
class Doc:
    level: str
    path: Path
    lines: list
    start: int
    overview: bool = False
    topics: list = field(default_factory=list)

    def body(self):
        """(line number, text) pairs from the document title on, skipping any golden-example preamble."""
        return [(i + 1, self.lines[i]) for i in range(self.start, len(self.lines))]

    def prose(self, include_fenced=False):
        """Body lines outside header lines, with link targets removed.

        Other fenced blocks only when asked; a mermaid fence always, reduced to what a reader sees. Never the fences.
        """
        result, fence = [], None
        for number, text in self.body():
            if text.lstrip().startswith("```"):
                fence = None if fence is not None else text.lstrip()[3:].strip()
                continue
            if text.startswith(HEADER_PREFIXES):
                continue
            if fence == "mermaid":
                text = mermaid_prose(text)
                if not text:
                    continue
            elif fence is not None and not include_fenced:
                continue
            result.append((number, LINK_TARGET.sub("]", text)))
        return result

    def section(self, title, level="## "):
        """Body lines under the heading `title` up to the next heading of the same or higher level."""
        result, inside = [], False
        stop = tuple("#" * n + " " for n in range(1, len(level)))
        for number, text in self.body():
            if text.startswith(level + title) and text[len(level):].strip() == title:
                inside = True
                continue
            if inside and text.startswith(stop):
                break
            if inside:
                result.append((number, text))
        return result

    def headings(self, level="## "):
        return [(n, t[len(level):].strip()) for n, t in self.body() if t.startswith(level)]

    def header_line(self, prefix):
        """A header line from the top of the file; a Level 1 guide keeps most of them in the About section."""
        candidates = self.body()[:20] + (self.section(ABOUT) if self.level == GUIDE else [])
        return next(((n, t) for n, t in candidates if t.startswith(prefix)), None)

    def required_sections(self):
        return (OVERVIEW_SECTIONS if self.overview else REQUIRED_SECTIONS)[self.level]

    def is_flow_section(self, title):
        if self.overview:
            return title == OVERVIEW_FLOW_PARENT
        if self.level == GUIDE:
            return title.startswith("For ") or title == AUTOMATIC_WORK
        return title == FLOW_PARENT[self.level]

    def is_area_guide(self):
        return self.level == GUIDE and not self.overview

    def family(self):
        """This document plus its Level 3 topic siblings."""
        return [self] + self.topics


def mermaid_prose(text):
    """What a reader sees on a diagram line: its quoted labels and the text after a colon."""
    seen = QUOTED_LABEL.findall(text)
    if ":" in text:
        seen.append(text.split(":", 1)[1])
    return " ".join(seen)


def load(level, path, overview=False):
    lines = path.read_text(encoding="utf-8").splitlines()
    anchor = next((i for i, t in enumerate(lines) if t.startswith("**Levels")), 0)
    start = next((i for i in range(anchor, -1, -1) if lines[i].startswith("# ")), 0)
    return Doc(level, path, lines, start, overview)


def table_rows(lines):
    return [(n, [c.strip() for c in t.strip().strip("|").split("|")]) for n, t in lines if t.lstrip().startswith("|")]


def data_rows(lines):
    """Table rows of a section holding one table, without its header and separator rows."""
    return table_rows(lines)[2:]


def level_of(target):
    if target.endswith(LEVEL_SUFFIX[BEHIND]):
        return BEHIND
    if target.endswith(LEVEL_SUFFIX[TECH]):
        return TECH
    return GUIDE


def check_levels_links(doc, check_targets):
    found = doc.header_line("**Levels")
    if found is None:
        return [Finding("ERROR", doc.path, 1, "levels-links", "no **Levels:** line")]
    number, text = found
    links = dict(re.findall(r"\[([^\]]+)\]\(([^)]+)\)", text))
    findings = [
        Finding("ERROR", doc.path, number, "levels-links", f"missing link '{label}'")
        for label in LEVEL_SUFFIX if label not in links
    ]
    findings += [
        Finding("ERROR", doc.path, number, "levels-links", f"'{label}' links to another level's file: {target}")
        for label, target in links.items() if label in LEVEL_SUFFIX and level_of(target) != label
    ]
    if check_targets:
        findings += [
            Finding("ERROR", doc.path, number, "levels-links", f"link target does not exist: {target}")
            for target in links.values() if not (doc.path.parent / target).exists()
        ]
    return findings


def check_header(doc):
    is_feature = doc.header_line("**Generated by") is not None
    required = ["**Created:**"] + ([] if is_feature else ["**Owned by:**", "**Derived from:**"])
    findings = [
        Finding("ERROR", doc.path, doc.start + 1, "header", f"missing {name}")
        for name in required if doc.header_line(name) is None
    ]
    if doc.is_area_guide() and not is_feature:
        about = [text for _, text in doc.section(ABOUT) if text.strip()]
        if not about or not AREA_ID_LINE.match(about[0]):
            findings.append(Finding("ERROR", doc.path, doc.start + 1, "header", f"{ABOUT} must open with **Id:** AREA-nnn"))
    return findings


def check_audience(doc):
    found = doc.header_line("**Audience:**")
    if found is None:
        return [Finding("ERROR", doc.path, doc.start + 1, "audience", "missing **Audience:** line")]
    number, text = found
    value = text.replace("**Audience:**", "").strip()
    if value not in ("shareable", "internal"):
        return [Finding("ERROR", doc.path, number, "audience", f"value must be shareable or internal, got '{value}'")]
    if value == EXPECTED_AUDIENCE[doc.level]:
        return []
    if doc.level == BEHIND:
        return [Finding("WARN", doc.path, number, "audience", "Level 2 marked shareable — human promotion; confirm")]
    return [Finding("ERROR", doc.path, number, "audience", f"{doc.level} must be {EXPECTED_AUDIENCE[doc.level]}")]


def stamp(doc):
    for prefix in ("**Derived from", "**Generated by"):
        found = doc.header_line(prefix)
        match = found and SHA.search(found[1])
        if match:
            return match.group(1)
    return None


def check_stamp_agree(docs):
    stamps = [(doc, stamp(doc)) for doc in docs]
    findings = [
        Finding("WARN", doc.path, doc.start + 1, "stamp-agree", f"{doc.path.name} carries no commit sha")
        for doc, sha in stamps if sha is None
    ]
    if len({sha for _, sha in stamps if sha}) > 1:
        detail = ", ".join(f"{d.path.name}={s}" for d, s in stamps)
        findings.append(Finding("WARN", docs[0].path, docs[0].start + 1, "stamp-agree", f"commit stamps differ: {detail}"))
    return findings


def check_tags(doc):
    findings = []
    legend = {n for n, _ in doc.section("How to read this")} if doc.level == TECH else set()
    for number, text in doc.body():
        if "#confirmed" in text and doc.level != TECH:
            findings.append(Finding("ERROR", doc.path, number, "confirmed", "#confirmed is never a tier"))
        if "#confirmed" in text and doc.level == TECH and number not in legend:
            findings.append(Finding(
                "WARN", doc.path, number, "confirmed",
                "#confirmed is a human's promotion, not the agent's to change; confirm the agent did not write it",
            ))
        if doc.level != TECH and re.search(r"#(observed|inferred)\b", text):
            findings.append(Finding("ERROR", doc.path, number, "tier-tags", "tier tag outside Level 3"))
    return findings


def client_words(tech):
    """Lower-cased words of the first column of Level 3's vocabulary table: the client's own declared words."""
    return {
        word.lower()
        for t in tech.family() for _, cells in data_rows(t.section("Business ↔ code vocabulary"))
        for word in re.findall(r"\w+", cells[0])
    }


def declared(word, allowed):
    return word.lower() in allowed or word.lower() + "s" in allowed


def check_code_nouns(doc, allowed):
    findings = []
    checks = [
        (STATUS_CODE, "status code"),
        (HTTP_ROUTE, "HTTP verb and path"),
        (SOURCE_EXT, "source-file name"),
        (FILE_LINE, "file:line reference"),
        (re.compile("`"), "inline code"),
    ]
    for number, text in doc.prose(include_fenced=True):
        findings += [
            Finding("ERROR", doc.path, number, "code-nouns", f"{label} in {doc.level}")
            for pattern, label in checks if pattern.search(text)
        ]
        if RESPONSE_STATUS.search(text):
            findings.append(Finding("WARN", doc.path, number, "code-nouns", "status code next to a response word"))
        findings += [
            Finding("WARN", doc.path, number, "code-nouns", f"code identifier '{word}'")
            for word in IDENTIFIER.findall(text) if word not in IDENT_ALLOW and not declared(word, allowed)
        ]
    return findings


def check_jargon(doc, allowed):
    words = LEVEL_JARGON[doc.level]
    pattern = re.compile(r"\b(" + "|".join(re.escape(w) for w in words) + r")s?\b", re.IGNORECASE)
    return [
        Finding("ERROR", doc.path, number, "jargon", f"'{match.group(1)}' in {doc.level}")
        for number, text in doc.prose() for match in pattern.finditer(text) if not declared(match.group(1), allowed)
    ]


def check_defect_words(doc):
    return [
        Finding("WARN", doc.path, number, "defect-words", f"'{match.group(1)}' judges behaviour; state it neutrally")
        for number, text in doc.prose() for match in DEFECT_WORDS.finditer(QUOTED.sub("", text))
    ]


def check_guarantee_words(doc):
    return [
        Finding("WARN", doc.path, number, "guarantee-words",
                f"'{match.group(1)}' is a timing or delivery guarantee; it needs an evidence-index row, or reword")
        for number, text in doc.prose() for match in GUARANTEE_WORDS.finditer(QUOTED.sub("", text))
    ]


def check_internal_ids(doc):
    about = {n for n, _ in doc.section(ABOUT)}
    question_rows = {n for n, _ in table_rows(doc.section("Open questions"))}
    findings = []
    for number, text in doc.prose(include_fenced=True):
        if number in about:
            continue
        if number in question_rows:
            text = re.sub(r"^\s*\|[^|]*\|", "|", text)
        findings += [
            Finding("ERROR", doc.path, number, "internal-ids", f"internal id {match} outside {ABOUT}")
            for match in INTERNAL_ID.findall(text)
        ]
    return findings


def check_alerts(doc):
    findings = []
    for number, text in doc.body():
        found = ALERT.match(text)
        if found and found.group(1) not in ALERT_KINDS:
            findings.append(Finding("ERROR", doc.path, number, "alerts", f"alert kind [!{found.group(1)}] is not allowed"))
    return findings


def check_example(doc):
    if any(re.fullmatch(r"A .+ in numbers", title) for _, title in doc.headings()):
        return []
    return [
        Finding("WARN", doc.path, number, "example", f"task '{heading}' computes but has no **Example**")
        for number, heading, lines in flow_tasks(doc)
        if any(FORMULA.match(text) for _, text in lines) and not any(text.startswith("**Example**") for _, text in lines)
    ]


def ids_in(doc, section, prefix):
    return [(n, cells[0]) for n, cells in table_rows(doc.section(section)) if re.fullmatch(prefix + r"\d+", cells[0])]


def duplicates(pairs, rule):
    seen, findings = set(), []
    for doc, number, ident in pairs:
        if ident in seen:
            findings.append(Finding("ERROR", doc.path, number, rule, f"duplicate id {ident}"))
        seen.add(ident)
    return findings


def check_qid_unique(guide, behind, tech):
    q_pairs = [(d, n, i) for d in (guide, behind) for n, i in ids_in(d, "Open questions", "Q")]
    t_pairs = [(t, n, i) for t in tech.family() for n, i in ids_in(t, "Technical open questions", "T")]
    return duplicates(q_pairs, "qid-unique") + duplicates(t_pairs, "qid-unique")


def check_ref_resolves(guide, behind, tech):
    index = tech.section("Evidence index")
    index_lines = {n for n, _ in index}
    defined = {
        cells[0] for t in tech.family() for n, cells in table_rows(t.body())
        if not (t is tech and n in index_lines) and re.fullmatch(r"[A-Z]+\d+", cells[0])
    }
    questions = {i for d in (guide, behind) for _, i in ids_in(d, "Open questions", "Q")}
    findings = [
        Finding("ERROR", tech.path, n, "ref-resolves", f"{ident} is not a Level 3 row id")
        for n, text in index for pair in CITED_ID.findall(text) for ident in pair if ident and ident not in defined
    ]
    findings += [
        Finding("ERROR", t.path, n, "ref-resolves", f"{ident} is not an open question in Levels 1-2")
        for t in tech.family() for n, cells in table_rows(t.body())
        for ident in re.findall(r"\bQ\d+\b", " ".join(cells)) if ident not in questions
    ]
    return findings


def check_index_rows(tech):
    findings = []
    for n, cells in data_rows(tech.section("Evidence index")):
        row = " ".join(cells)
        evidence = cells[3] if len(cells) > 3 else ""
        if cells[0] not in INDEX_LEVELS:
            findings.append(Finding("ERROR", tech.path, n, "index-level", f"Level must be Guide or Behind the scenes, got '{cells[0]}'"))
        if "#inferred" in row and not re.search(r"\b[QT]\d+\b", evidence):
            findings.append(Finding("ERROR", tech.path, n, "index-evidence", "#inferred row names no Q or T id"))
        if "#observed" in row and evidence in EMPTY_EVIDENCE:
            findings.append(Finding("ERROR", tech.path, n, "index-evidence", "#observed row has no evidence"))
    return findings


def flow_tasks(doc):
    """(line number, heading, body lines) of each ### flow under the level's flow sections."""
    result, current, inside = [], None, False
    for number, text in doc.body():
        if text.startswith("## "):
            inside, current = doc.is_flow_section(text[3:].strip()), None
        elif not inside:
            continue
        elif text.startswith("### "):
            current = (number, text[4:].strip(), [])
            result.append(current)
        elif current:
            current[2].append((number, text))
    return result


def flows(doc):
    """Map each flow to (its highest step number, its number of outcomes under **What happens next**)."""
    result = {}
    for number, heading, lines in flow_tasks(doc):
        steps, outcomes, listing = 0, 0, False
        for _, text in lines:
            step = re.match(r"\s*(\d+)\.\s", text)
            if step:
                steps = max(steps, int(step.group(1)))
            if text.startswith("**"):
                listing = text.startswith("**What happens next")
            elif listing and re.match(r"[-*]\s", text):
                outcomes += 1
        result[(number, heading)] = (steps, outcomes)
    return result


def check_index(tech, doc):
    rows = [(n, cells) for n, cells in data_rows(tech.section("Evidence index")) if len(cells) >= 2]
    sections = [(n, cells[1]) for n, cells in rows if cells[0] == doc.level]
    findings = []
    for (number, heading), counts in flows(doc).items():
        cited = [(n, s) for n, s in sections if s == heading or s.startswith(heading + " · ")]
        if not cited:
            findings.append(Finding("ERROR", doc.path, number, "index-coverage", f"flow '{heading}' has no evidence-index row"))
        for n, section in cited:
            for pattern, available, kind in zip((STEP_CITE, OUTCOME_CITE), counts, ("step", "outcome")):
                match = pattern.search(section)
                highest = match and int(match.group(2) or match.group(1))
                if highest and highest > available:
                    findings.append(Finding("WARN", tech.path, n, "index-steps", f"'{section}' cites a {kind} beyond {available}"))
    return findings


def check_sections(doc):
    present = {title for d in doc.family() for _, title in d.headings()}
    findings = [
        Finding("ERROR", doc.path, doc.start + 1, "sections", f"missing section '## {title}'")
        for title in doc.required_sections() if title not in present
    ]
    if doc.is_area_guide() and not any(title.startswith("For ") for _, title in doc.headings()):
        findings.append(Finding("ERROR", doc.path, doc.start + 1, "sections", "missing a '## For <person>' section"))
    in_main = {title for _, title in doc.headings()}
    if doc.level == TECH and "Evidence index" in present and "Evidence index" not in in_main:
        findings.append(Finding("ERROR", doc.path, doc.start + 1, "sections", "'## Evidence index' must be in the main file"))
    return findings


def topic_paths(technical):
    stem = technical.name[: -len(".md")]
    return sorted(technical.parent.glob(stem + ".*.md"))


def lint_set(paths, check_targets):
    missing = [Finding("ERROR", p, 0, "set-complete", f"missing {level} file") for level, p in paths.items() if not p.is_file()]
    if missing:
        return missing
    overview = paths[GUIDE].name == OVERVIEW_NAME + LEVEL_SUFFIX[GUIDE]
    guide, behind, tech = (load(level, paths[level], overview) for level in (GUIDE, BEHIND, TECH))
    tech.topics = [load(TECH, p, overview) for p in topic_paths(paths[TECH])]
    docs = [guide, behind, tech]
    allowed = client_words(tech)
    findings = []
    for doc in docs:
        findings += check_levels_links(doc, check_targets) + check_header(doc) + check_audience(doc)
        findings += check_tags(doc) + check_sections(doc)
    for topic in tech.topics:
        findings += check_tags(topic)
    for doc in (guide, behind):
        findings += check_code_nouns(doc, allowed) + check_jargon(doc, allowed) + check_alerts(doc)
        findings += check_defect_words(doc) + check_guarantee_words(doc) + check_index(tech, doc)
    findings += (check_internal_ids(guide) if guide.is_area_guide() else []) + check_example(guide)
    findings += check_stamp_agree(docs) + check_index_rows(tech)
    findings += check_qid_unique(guide, behind, tech) + check_ref_resolves(guide, behind, tech)
    return findings


def sets_in(folder):
    names = {
        (path.parent, path.name[: -len(LEVEL_SUFFIX[level])])
        for level in (BEHIND, TECH) for path in folder.rglob("*" + LEVEL_SUFFIX[level])
    }
    for parent, name in sorted(names):
        yield {level: parent / (name + suffix) for level, suffix in LEVEL_SUFFIX.items()}


def lint_dir(folder):
    sets = list(sets_in(folder)) if folder.is_dir() else []
    if not sets:
        return [Finding("ERROR", folder, 0, "no-sets", "no documentation set found")]
    return [f for paths in sets for f in lint_set(paths, True)]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dir", type=Path, help="folder to search for sets")
    parser.add_argument("files", nargs="*", type=Path, help="guide, behind-the-scenes and technical files")
    args = parser.parse_args(argv)
    if args.dir is not None:
        findings = lint_dir(args.dir)
    elif len(args.files) == 3:
        findings = lint_set(dict(zip((GUIDE, BEHIND, TECH), args.files)), False)
    else:
        parser.error("give --dir <folder> or exactly three files")
    for finding in findings:
        print(finding)
    errors = sum(f.severity == "ERROR" for f in findings)
    print(f"doc-lint: {errors} error(s), {len(findings) - errors} warning(s)", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
