REQUIRED_SECTIONS = ["In short", "Who uses it", "Open questions", "About this document"]
OVERVIEW_SECTIONS = [
    "In short", "Who uses it", "The journey", "Areas, by who uses them", "End-to-end flows", "What is not documented",
    "About this document",
]
DELIVERY_SECTIONS = ["Not delivered", "About this document"]
DELIVERY_TITLE = "# What was delivered"
AUTOMATIC_WORK = "What happens automatically"
ABOUT = "About this document"
IN_SHORT = "In short"
RULES = "Rules and limits"
RULES_COLUMN = "Where you meet it"
CALCULATED = "How it is calculated"
SEE_ALSO = "See also"
OVERVIEW_FLOW_PARENT = "End-to-end flows"
WORD_LIMIT = 2500
MAX_STEPS, MAX_OUTCOMES, MAX_ALERTS, MAX_KEY_IDEAS, MAX_GOOD_TO_KNOW, MAX_SENTENCE_WORDS = 7, 5, 1, 6, 6, 30
MAX_IN_SHORT, MAX_SEE_ALSO = 5, 6
MAX_SCREENSHOTS = 6
SCREENSHOT_TYPES = (".png", ".jpg", ".jpeg", ".webp")
MERMAID_FIRST_LINES = ("stateDiagram-v2", "flowchart LR")
