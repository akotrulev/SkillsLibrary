NUMBER = re.compile(r"(?<![\w.-])\d+(?:[.,]\d+)*")
LIST_NUMBER = re.compile(r"^\s*\d+\.\s+")


@dataclass(frozen=True)
class Finding:
    severity: str
    path: Path
    line: int
    rule: str
    message: str

    def __str__(self):
        return f"{self.severity} {self.path}:{self.line} {self.rule} {self.message}"


@dataclass
class Doc:
    path: Path
    lines: list
    start: int

    @property
    def overview(self):
        return self.path.name == OVERVIEW_NAME

    @property
    def delivery(self):
        return any(line.startswith(DELIVERY_TITLE) for line in self.lines[:1])

    def body(self):
        """(line number, text) pairs from the document title on, skipping any golden-example preamble."""
        return [(i + 1, self.lines[i]) for i in range(self.start, len(self.lines))]

    def prose(self, include_fenced=False):
        """Body lines outside header lines, with link targets removed.

        Other fenced blocks only when asked; a mermaid fence always, reduced to what a reader sees. Never the fences.
        """
        result, fence = [], None
        for number, text in self.body():
            if text.lstrip().startswith("```"):
                fence = None if fence is not None else text.lstrip()[3:].strip()
                continue
            if text.startswith(HEADER_PREFIXES):
                continue
            if fence == "mermaid":
                text = mermaid_prose(text)
                if not text:
                    continue
            elif fence is not None and not include_fenced:
                continue
            result.append((number, LINK_TARGET.sub("]", text)))
        return result

    def section(self, title, level="## "):
        """Body lines under the heading `title` up to the next heading of the same or higher level."""
        result, inside = [], False
        stop = tuple("#" * n + " " for n in range(1, len(level)))
        for number, text in self.body():
            if text.startswith(level + title) and text[len(level):].strip() == title:
                inside = True
                continue
            if inside and text.startswith(stop):
                break
            if inside:
                result.append((number, text))
        return result

    def headings(self, level="## "):
        return [(n, t[len(level):].strip()) for n, t in self.body() if t.startswith(level)]

    def header_lines(self):
        """The metadata lines: the top of the file and the About section."""
        return self.body()[:20] + self.section(ABOUT)

    def header_line(self, prefix):
        return next(((n, t) for n, t in self.header_lines() if t.startswith(prefix)), None)

    def heading_line(self, title):
        return next((n for n, t in self.headings() if t == title), None)

    def reader_lines(self):
        """Body lines a reader reads: outside fenced blocks, header lines and About."""
        skipped = {n for n, _ in self.section(ABOUT)}
        result, fenced = [], False
        for number, text in self.body():
            if text.lstrip().startswith("```"):
                fenced = not fenced
            elif not fenced and number not in skipped and not text.startswith(HEADER_PREFIXES):
                result.append((number, LINK_TARGET.sub("]", text)))
        return result

    def is_flow_section(self, title):
        if self.overview:
            return title == OVERVIEW_FLOW_PARENT
        return title.startswith("For ") or title == AUTOMATIC_WORK


def mermaid_prose(text):
    """What a reader sees on a diagram line: its quoted labels and the text after a colon."""
    seen = QUOTED_LABEL.findall(text)
    if ":" in text:
        seen.append(text.split(":", 1)[1])
    return " ".join(seen)


def load(path):
    """The guide starts at the last # title before its first ## heading, so a golden-example preamble is skipped."""
    lines = path.read_text(encoding="utf-8").splitlines()
    first_section = next((i for i, t in enumerate(lines) if t.startswith("## ")), len(lines))
    start = next((i for i in range(first_section - 1, -1, -1) if lines[i].startswith("# ")), 0)
    return Doc(path, lines, start)


def table_rows(lines):
    return [(n, [c.strip() for c in t.strip().strip("|").split("|")]) for n, t in lines if t.lstrip().startswith("|")]


def client_words(doc):
    """Lower-cased words of the guide's bold spans: screen labels and key-idea terms, the client's own words."""
    return {word.lower() for _, text in doc.prose() for span in BOLD.findall(text) for word in re.findall(r"\w+", span)}


def declared(word, allowed):
    return word.lower() in allowed or word.lower() + "s" in allowed


def check_header(doc):
    if doc.header_line("**Created:**") is None:
        return [Finding("ERROR", doc.path, doc.start + 1, "header", "missing **Created:**")]
    return []


def stamp_comment(doc, kind):
    """(line number, fields) of the last-line stamp comment of that kind, or None."""
    for number, text in reversed(doc.body()):
        found = STAMP_COMMENT.match(text.strip())
        if found and found.group(1) == kind:
            parts = (part.partition(": ") for part in found.group(2).split(" · "))
            return number, {key: value for key, _, value in parts}
    return None


def old_about_lines(doc):
    return sorted({(n, t) for n, t in doc.header_lines() if t.startswith(OLD_ABOUT_LINES)})


def legacy_stamp(old_lines):
    """The stamp fields an old guide's visible lines carry: sha, audience and id."""
    fields = {}
    for _, text in old_lines:
        sha = SHA.search(text)
        if text.startswith(("**Derived from", "**Generated by")) and sha:
            agent = FEATURE_AGENT if text.startswith("**Generated by") else "documenter"
            fields["source"] = f"{agent} @ {sha.group(1)}"
        elif text.startswith("**Audience:**"):
            fields["audience"] = text.replace("**Audience:**", "").strip()
        elif text.startswith("**Id:**"):
            fields["id"] = text.replace("**Id:**", "").strip()
    return fields


def stamp_gaps(fields):
    gaps = [] if STAMP_SOURCE.fullmatch(fields.get("source", "")) else ["source: <agent> @ <sha>"]
    return gaps + ([] if fields.get("audience") == "shareable" else ["audience: shareable"])


def stamp_findings(doc, number, gaps):
    return [Finding("ERROR", doc.path, number, "stamp", f"the stamp comment lacks {gap}") for gap in gaps]


def check_stamp(doc):
    found = stamp_comment(doc, "guide")
    old_lines = old_about_lines(doc)
    if found is None and old_lines:
        found = doc.start + 1, legacy_stamp(old_lines)
    if found is None:
        return [Finding("ERROR", doc.path, doc.start + 1, "stamp", "missing the stamp comment '<!-- guide · … -->' as the last line")]
    number, fields = found
    gaps = stamp_gaps(fields)
    is_area = not doc.overview and not fields.get("source", "").startswith(FEATURE_AGENT)
    if is_area and not AREA_ID.fullmatch(fields.get("id", "")):
        gaps.append("id: AREA-nnn")
    return stamp_findings(doc, number, gaps)


def check_delivery_stamp(doc):
    found = stamp_comment(doc, "delivery")
    if found is None:
        return [Finding("ERROR", doc.path, doc.start + 1, "stamp", "missing the stamp comment '<!-- delivery · … -->' as the last line")]
    number, fields = found
    gaps = ([] if fields.get("plan") else ["plan: <number>"]) + stamp_gaps(fields)
    return stamp_findings(doc, number, gaps)


def check_about_shape(doc):
    return [
        Finding("WARN", doc.path, number, "about-shape", f"the {text.split('**')[1].rstrip(':')} line is the old shape; move it into the stamp comment")
        for number, text in old_about_lines(doc)
    ]


def check_tags(doc):
    findings = []
    for number, text in doc.body():
        if "#confirmed" in text:
            findings.append(Finding("ERROR", doc.path, number, "confirmed", "#confirmed is never a tier"))
        if re.search(r"#(observed|inferred)\b", text):
            findings.append(Finding("ERROR", doc.path, number, "tier-tags", "tier tag in a guide"))
    return findings


def check_code_nouns(doc, allowed):
    findings = []
    checks = [
        (STATUS_CODE, "status code"),
        (HTTP_ROUTE, "HTTP verb and path"),
        (SOURCE_EXT, "source-file name"),
        (FILE_LINE, "file:line reference"),
        (re.compile("`"), "inline code"),
    ]
    for number, text in doc.prose(include_fenced=True):
        findings += [
            Finding("ERROR", doc.path, number, "code-nouns", f"{label} in a guide")
            for pattern, label in checks if pattern.search(text)
        ]
        if RESPONSE_STATUS.search(text):
            findings.append(Finding("WARN", doc.path, number, "code-nouns", "status code next to a response word"))
        findings += [
            Finding("WARN", doc.path, number, "code-nouns", f"code identifier '{word}'")
            for word in IDENTIFIER.findall(text) if word not in IDENT_ALLOW and not declared(word, allowed)
        ]
    return findings


def check_jargon(doc, allowed):
    pattern = re.compile(r"\b(" + "|".join(re.escape(w) for w in JARGON) + r")s?\b", re.IGNORECASE)
    return [
        Finding("ERROR", doc.path, number, "jargon", f"'{match.group(1)}' in a guide")
        for number, text in doc.prose() for match in pattern.finditer(text) if not declared(match.group(1), allowed)
    ]


def check_defect_words(doc):
    return [
        Finding("WARN", doc.path, number, "defect-words", f"'{match.group(1)}' judges behaviour; state it neutrally")
        for number, text in doc.prose() for match in DEFECT_WORDS.finditer(QUOTED.sub("", text))
    ]


def check_guarantee_words(doc):
    return [
        Finding("WARN", doc.path, number, "guarantee-words",
                f"'{match.group(1)}' is a timing or delivery guarantee; keep it only where the code shows it, or reword")
        for number, text in doc.prose() for match in GUARANTEE_WORDS.finditer(QUOTED.sub("", text))
    ] + [
        Finding("WARN", doc.path, number, "guarantee-words",
                f"'{match.group(0).strip()}' promises a roadmap no code shows; state what exists, or ask")
        for number, text in doc.prose() for match in ROADMAP_PROMISE.finditer(QUOTED.sub("", text))
    ]


def check_internal_ids(doc):
    question_rows = {n for n, _ in table_rows(doc.section("Open questions"))}
    findings = []
    for number, text in doc.prose(include_fenced=True):
        if number in question_rows:
            text = re.sub(r"^\s*\|[^|]*\|", "|", text)
        findings += [
            Finding("ERROR", doc.path, number, "internal-ids", f"internal id {match} outside the stamp comment")
            for match in INTERNAL_ID.findall(text)
        ]
    return findings


def check_alerts(doc):
    findings = []
    for number, text in doc.body():
        found = ALERT.match(text)
        if found and found.group(1) not in ALERT_KINDS:
            findings.append(Finding("ERROR", doc.path, number, "alerts", f"alert kind [!{found.group(1)}] is not allowed"))
    return findings


def flow_tasks(doc):
    """(line number, section title, heading, body lines) of each ### task under the guide's task sections."""
    result, current, section = [], None, None
    for number, text in doc.body():
        if text.startswith("## "):
            title = text[3:].strip()
            section, current = (title if doc.is_flow_section(title) else None), None
        elif section is None:
            continue
        elif text.startswith("### "):
            current = (number, section, text[4:].strip(), [])
            result.append(current)
        elif current:
            current[3].append((number, text))
    return result


def before_example(lines):
    return list(itertools.takewhile(lambda item: not item[1].startswith("**Example**"), lines))


def check_formula_place(doc):
    findings = []
    for _, section, heading, lines in flow_tasks(doc):
        formula = next((n for n, text in before_example(lines) if FORMULA.match(text)), None)
        if section.startswith("For ") and formula is not None:
            findings.append(Finding("WARN", doc.path, formula, "formula-place",
                                    f"task '{heading}' holds a formula before its **Example**; move it under '## {CALCULATED}'"))
    return findings


def check_example(doc):
    calculated = doc.heading_line(CALCULATED)
    has_numbers = any(re.fullmatch(r"A .+ in numbers", title) for _, title in doc.headings())
    has_example = any(text.startswith("**Example**") for _, _, _, lines in flow_tasks(doc) for _, text in lines)
    if calculated is None or has_numbers or has_example:
        return []
    return [Finding("WARN", doc.path, calculated, "example", f"'{CALCULATED}' has no **Example** in any task and no 'A ... in numbers' section")]


def check_automatic(doc):
    findings = []
    for number, section, heading, lines in flow_tasks(doc):
        if section != AUTOMATIC_WORK:
            continue
        texts = [text for _, text in lines]
        if not any(text.startswith("**When:**") for text in texts):
            findings.append(Finding("ERROR", doc.path, number, "automatic", f"'{heading}' has no **When:** line"))
        if any(text.startswith(("**Trigger:**", "**Result:**")) for text in texts):
            findings.append(Finding("WARN", doc.path, number, "automatic", f"'{heading}' is the old shape; write When and What people notice"))
    return findings


def check_in_short(doc):
    heading = doc.heading_line(IN_SHORT)
    if heading is None:
        return []
    bullets = [n for n, text in doc.section(IN_SHORT) if re.match(r"\s*[-*]\s", text)]
    if not bullets:
        return [Finding("ERROR", doc.path, heading, "in-short", f"'{IN_SHORT}' holds no bullet; write three to {MAX_IN_SHORT}")]
    if len(bullets) > MAX_IN_SHORT:
        return [Finding("WARN", doc.path, heading, "in-short", f"{len(bullets)} bullets; at most {MAX_IN_SHORT}")]
    return []


def check_rules(doc):
    heading = doc.heading_line(RULES)
    if heading is None:
        return [Finding("WARN", doc.path, doc.start + 1, "rules", f"no '{RULES}'; say in the report that the trace found no rule")]
    rows = table_rows(doc.section(RULES))
    if rows and RULES_COLUMN not in rows[0][1]:
        return [Finding("WARN", doc.path, rows[0][0], "rules", f"the rules table has no '{RULES_COLUMN}' column")]
    return []


def check_questions(doc):
    rows = table_rows(doc.section("Open questions"))
    if rows and "Answer" not in rows[0][1]:
        return [Finding("ERROR", doc.path, rows[0][0], "questions", "the open-questions table has no Answer column")]
    return []


def check_renamed_section(doc):
    return [
        Finding("WARN", doc.path, number, "renamed-section", f"'## Related areas' is now '## {SEE_ALSO}': a list of up to {MAX_SEE_ALSO} guides, one reason each")
        for number, title in doc.headings() if title == "Related areas"
    ]


def check_task_unique(doc):
    seen, findings = set(), []
    for number, _, heading, _ in flow_tasks(doc):
        if heading in seen:
            findings.append(Finding("ERROR", doc.path, number, "task-unique", f"duplicate task heading '{heading}'"))
        seen.add(heading)
    return findings


def check_length(doc):
    count = sum(len(WORD.findall(text)) for _, text in doc.reader_lines())
    if count <= WORD_LIMIT:
        return []
    return [Finding("ERROR", doc.path, doc.start + 1, "length",
                    f"{count} words; a guide holds at most {WORD_LIMIT} — cut, or split the administrators' tasks out")]


def counts(lines):
    """(highest step number, outcomes under **What happens next** or **What people notice**) of one task's lines."""
    steps, outcomes, listing = 0, 0, False
    for _, text in lines:
        step = re.match(r"\s*(\d+)\.\s", text)
        if step:
            steps = max(steps, int(step.group(1)))
        if text.startswith("**"):
            listing = text.startswith(OUTCOME_MARKERS)
        elif listing and re.match(r"[-*]\s", text):
            outcomes += 1
    return steps, outcomes


def check_limits(doc):
    findings = []
    for number, _, heading, body in flow_tasks(doc):
        steps, outcomes = counts(body)
        alerts = sum(bool(ALERT.match(text)) for _, text in body)
        for count, limit, what in ((steps, MAX_STEPS, "steps"), (outcomes, MAX_OUTCOMES, "outcomes"), (alerts, MAX_ALERTS, "alerts")):
            if count > limit:
                findings.append(Finding("WARN", doc.path, number, "limits", f"task '{heading}' has {count} {what}; at most {limit}"))
    ideas = [n for n, text in doc.section("How it fits together") if re.match(r"\s*[-*]\s+\*\*", text)]
    if len(ideas) > MAX_KEY_IDEAS:
        findings.append(Finding("WARN", doc.path, ideas[0], "limits", f"{len(ideas)} key ideas; at most {MAX_KEY_IDEAS}"))
    entries = [n for n, text in doc.section("Good to know") if text.startswith("### ")]
    if len(entries) > MAX_GOOD_TO_KNOW:
        findings.append(Finding("WARN", doc.path, entries[0], "limits", f"{len(entries)} Good to know entries; at most {MAX_GOOD_TO_KNOW}"))
    see_also = [n for n, text in doc.section(SEE_ALSO) if re.match(r"[-*]\s", text)]
    if len(see_also) > MAX_SEE_ALSO:
        findings.append(Finding("WARN", doc.path, see_also[0], "limits", f"{len(see_also)} See also entries; at most {MAX_SEE_ALSO}"))
    return findings


def sentences(doc):
    """(line number, sentence) from prose paragraphs and list items; tables, formulas, headings and images are skipped."""
    blocks, current = [], None
    for number, text in doc.reader_lines():
        text = re.sub(r"^\s*>\s*(?:\[!\w+\])?", "", text)
        if not text.strip() or text.startswith(("|", "#", "![")) or FORMULA.match(text):
            current = None
            continue
        if current is None or LIST_ITEM.match(text):
            current = [number, ""]
            blocks.append(current)
        current[1] += " " + LIST_ITEM.sub("", text, count=1).strip()
    return [(number, part) for number, block in blocks for part in SENTENCE_BREAK.split(block.strip())]


def check_long_sentence(doc):
    return [
        Finding("WARN", doc.path, number, "long-sentence", f"{len(sentence.split())} words; split it at {MAX_SENTENCE_WORDS}")
        for number, sentence in sentences(doc) if len(sentence.split()) > MAX_SENTENCE_WORDS
    ]


def check_diagram(doc):
    fences, current = [], None
    for number, text in doc.body():
        if text.lstrip().startswith("```"):
            current = None if current is not None else (number, text.lstrip()[3:].strip(), [])
            if current is not None and current[1] == "mermaid":
                fences.append(current)
        elif current is not None:
            current[2].append((number, text))
    findings = [
        Finding("ERROR", doc.path, fences[1][0], "diagram", f"{len(fences)} mermaid diagrams; a guide draws one")
    ] if len(fences) > 1 else []
    for number, _, lines in fences:
        first = next(((n, t.strip()) for n, t in lines if t.strip()), (number, ""))
        if first[1] not in MERMAID_FIRST_LINES:
            findings.append(Finding("ERROR", doc.path, first[0], "diagram", f"first line '{first[1]}' must be stateDiagram-v2 or flowchart LR"))
        if first[1] == "flowchart LR":
            findings += [
                Finding("ERROR", doc.path, n, "diagram", "a flowchart node label must be in double quotes")
                for n, text in lines for node in FLOWCHART_NODE.finditer(text) if node.group(1) != '"'
            ]
    return findings


def check_qid_unique(doc):
    seen, findings = set(), []
    for number, cells in table_rows(doc.section("Open questions")):
        ident = cells[0]
        if re.fullmatch(r"Q\d+", ident):
            if ident in seen:
                findings.append(Finding("ERROR", doc.path, number, "qid-unique", f"duplicate id {ident}"))
            seen.add(ident)
    return findings


def check_sections(doc):
    present = {title for _, title in doc.headings()}
    required = DELIVERY_SECTIONS if doc.delivery else OVERVIEW_SECTIONS if doc.overview else REQUIRED_SECTIONS
    findings = [
        Finding("ERROR", doc.path, doc.start + 1, "sections", f"missing section '## {title}'")
        for title in required if title not in present
    ]
    if not doc.overview and not doc.delivery and not any(title.startswith("For ") for title in present):
        findings.append(Finding("ERROR", doc.path, doc.start + 1, "sections", "missing a '## For <person>' section"))
    return findings


def images(doc):
    """(line number, alt text, target) of each image outside fenced blocks."""
    result, fenced = [], False
    for number, text in doc.body():
        if text.lstrip().startswith("```"):
            fenced = not fenced
        elif not fenced:
            result += [(number, alt, target) for alt, target in IMAGE.findall(text)]
    return result


def check_screenshots(doc):
    person_tasks = [task for task in flow_tasks(doc) if task[1].startswith("For ")]
    task_of = {n: task for task in person_tasks for n, _ in task[3]}
    findings, seen, per_task = [], set(), {}
    found = images(doc)
    for number, alt, target in found:
        task = task_of.get(number)
        if task is None:
            findings.append(Finding("ERROR", doc.path, number, "screenshots", "a screenshot sits only in a person's task"))
        elif not any(text.startswith("**Where:**") for _, text in task[3]):
            findings.append(Finding("ERROR", doc.path, number, "screenshots", f"task '{task[2]}' has no **Where:** line, so no screen to show"))
        elif per_task.setdefault(task[0], number) != number:
            findings.append(Finding("ERROR", doc.path, number, "screenshots", f"task '{task[2]}' has a second screenshot; at most one"))
        if not alt.strip():
            findings.append(Finding("ERROR", doc.path, number, "screenshots", "empty alt text; say what the screen shows"))
        if not target.lower().endswith(SCREENSHOT_TYPES):
            findings.append(Finding("ERROR", doc.path, number, "screenshots", f"'{target}' is not a .png, .jpg, .jpeg or .webp file"))
        elif not (doc.path.parent / target).is_file():
            findings.append(Finding("ERROR", doc.path, number, "screenshots", f"file does not exist: {target}"))
        if target in seen:
            findings.append(Finding("ERROR", doc.path, number, "screenshots", f"the same screenshot twice: {target}"))
        seen.add(target)
    if len(found) > MAX_SCREENSHOTS:
        findings.append(Finding("WARN", doc.path, found[MAX_SCREENSHOTS][0], "screenshots",
                                f"{len(found)} screenshots; at most {MAX_SCREENSHOTS} — keep the ones that save the most words"))
    waived = any(WAIVED.match(text) for _, text in doc.section(ABOUT))
    pending = next((n for n, text in doc.section(ABOUT) if PENDING.match(text)), None)
    has_screen = any(text.startswith("**Where:**") for task in person_tasks for _, text in task[3])
    if has_screen and not found and not waived and pending is None:
        findings.append(Finding("ERROR", doc.path, doc.start + 1, "screenshots",
                                "tasks have screens and the guide holds no screenshot; capture them, or record the person's waiver"))
    if pending is not None:
        findings.append(Finding("WARN", doc.path, pending, "screenshots-pending", "screenshots are pending; capture them before the guide counts as finished"))
    return findings


def check_levels_line(doc):
    return [
        Finding("WARN", doc.path, n, "retired-level", "the **Levels:** line links retired levels; remove it")
        for n, text in doc.body()[:20] if text.startswith("**Levels")
    ]


def is_old_shape(doc):
    titles = {title for _, title in doc.headings()}
    old_marker = "The areas" if doc.overview else "How it works"
    return old_marker in titles and "Who uses it" not in titles


def check_index_line(index, lines, folder, guide_path):
    target = guide_path.relative_to(folder).as_posix()
    mine = [(n, text) for n, text in enumerate(lines, 1) if f"]({target})" in text]
    if len(mine) != 1:
        return [Finding("ERROR", index, mine[0][0] if mine else 1, "index-line", f"{len(mine)} lines link {target}; exactly one")]
    number, text = mine[0]
    match = INDEX_LINE.match(text)
    if not match:
        return [Finding("ERROR", index, number, "index-line", f"the line for {target} is not of the INDEX line shape")]
    if len(match["what"].split()) > MAX_INDEX_WORDS:
        return [Finding("ERROR", index, number, "index-line", f"description over {MAX_INDEX_WORDS} words")]
    return []


def fact_lines(text):
    """(line number, kind, fact) of each number and quoted message a reader meets: header lines, link targets and list numbers are not facts."""
    result = []
    for number, line in enumerate(text.splitlines(), 1):
        if line.startswith(HEADER_PREFIXES):
            continue
        line = LIST_NUMBER.sub("", LINK_TARGET.sub("]", line))
        result += [(number, "number", found) for found in NUMBER.findall(line)]
        result += [(number, "message", " ".join(quote[1:-1].split())) for quote in QUOTED.findall(line)]
    return result


def lost_facts(old_text, new_text):
    """(line, kind, fact) of each fact in `old_text` that `new_text` no longer holds, first sighting only."""
    squashed = " ".join(new_text.split())
    numbers = set(NUMBER.findall(new_text))
    lost, seen = [], set()
    for number, kind, fact in fact_lines(old_text):
        kept = fact in numbers if kind == "number" else fact in squashed
        if not kept and (kind, fact) not in seen:
            seen.add((kind, fact))
            lost.append((number, kind, fact))
    return lost


def git_show(rev, path):
    """The file's text at `rev`, or None when that revision has no such file."""
    shown = subprocess.run(["git", "-C", str(path.parent), "show", f"{rev}:./{path.name}"], capture_output=True, text=True)
    return shown.stdout if shown.returncode == 0 else None


def revision_exists(rev, folder):
    checked = subprocess.run(["git", "-C", str(folder), "rev-parse", "--verify", "--quiet", rev + "^{commit}"], capture_output=True)
    return checked.returncode == 0


def check_kept(doc, rev):
    old = git_show(rev, doc.path)
    if old is None:
        return []
    return [
        Finding("WARN", doc.path, line, "fact-kept",
                f"{kind} '{fact}' from {rev} is no longer in the guide; restore it, or name the code change that removed it")
        for line, kind, fact in lost_facts(old, "\n".join(doc.lines))
    ]


def lint_delivery(doc):
    allowed = client_words(doc)
    findings = check_delivery_stamp(doc) + check_tags(doc) + check_sections(doc)
    findings += check_code_nouns(doc, allowed) + check_jargon(doc, allowed)
    return findings + check_defect_words(doc) + check_guarantee_words(doc) + check_long_sentence(doc)


def lint_guide(path, kept_from=None):
    doc = load(path)
    if doc.delivery:
        return lint_delivery(doc)
    if is_old_shape(doc):
        return [Finding("WARN", doc.path, doc.start + 1, "old-shape",
                        "written in the old layout; update it in place into the current shape — no other check runs on it")]
    allowed = client_words(doc)
    findings = check_header(doc) + check_stamp(doc) + check_about_shape(doc) + check_tags(doc) + check_sections(doc)
    findings += check_in_short(doc) + check_code_nouns(doc, allowed) + check_jargon(doc, allowed) + check_alerts(doc)
    findings += check_defect_words(doc) + check_guarantee_words(doc) + check_task_unique(doc) + check_length(doc)
    findings += check_diagram(doc) + check_formula_place(doc) + check_example(doc) + check_automatic(doc)
    findings += check_qid_unique(doc) + check_questions(doc) + check_screenshots(doc) + check_levels_line(doc)
    if not doc.overview:
        findings += check_internal_ids(doc) + check_limits(doc) + check_long_sentence(doc)
        findings += check_rules(doc) + check_renamed_section(doc)
    if kept_from:
        findings += check_kept(doc, kept_from)
    return findings


def is_retired(path):
    return path.name.endswith(RETIRED_SUFFIXES) or bool(RETIRED_TOPIC.search(path.name))


def is_guide(path):
    text = path.read_text(encoding="utf-8")
    return (
        text.startswith(DELIVERY_TITLE)
        or bool(re.search(r"^## About this document\s*$", text, re.MULTILINE))
        or bool(re.search(r"^\*\*Levels:", text, re.MULTILINE))
    )


def scan(folder):
    """(guides, retired level files) under the folder, skipping trace and screenshot folders."""
    paths = [p for p in sorted(folder.rglob("*.md")) if not SKIPPED_FOLDERS.intersection(p.relative_to(folder).parts)]
    retired = [p for p in paths if is_retired(p)]
    guides = [p for p in paths if not is_retired(p) and is_guide(p)]
    return guides, retired


def lint_dir(folder, kept_from=None):
    guides, retired = scan(folder) if folder.is_dir() else ([], [])
    if not guides:
        return [Finding("ERROR", folder, 0, "no-guides", "no guide found")]
    findings = [
        Finding("WARN", path, 1, "retired-level", "Levels 2 and 3 are retired; delete this file once its guide is updated")
        for path in retired
    ]
    index = folder / "INDEX.md"
    index_lines = index.read_text(encoding="utf-8").splitlines() if index.is_file() else None
    for path in guides:
        found = lint_guide(path, kept_from)
        findings += found
        old = any(f.rule == "old-shape" for f in found)
        if index_lines is not None and not old and path.relative_to(folder).parts[0] == "areas":
            findings += check_index_line(index, index_lines, folder, path)
    return findings


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dir", type=Path, help="folder to search for guides")
    parser.add_argument("files", nargs="*", type=Path, help="guides to lint")
    parser.add_argument("--kept-from", metavar="GIT_REV", help="report facts each guide held at that revision and holds no longer")
    args = parser.parse_args(argv)
    if args.dir is None and not args.files:
        parser.error("give --dir <folder> or one or more guides")
    if args.kept_from and not revision_exists(args.kept_from, args.dir or args.files[0].parent):
        parser.error(f"revision {args.kept_from} not found")
    if args.dir is not None:
        findings = lint_dir(args.dir, args.kept_from)
    else:
        findings = [f for path in args.files for f in lint_guide(path, args.kept_from)]
    for finding in findings:
        print(finding)
    errors = sum(f.severity == "ERROR" for f in findings)
    print(f"doc-lint: {errors} error(s), {len(findings) - errors} warning(s)", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
