#!/usr/bin/env python3
"""Deterministic lint for a three-level documentation set (guide, behind the scenes, technical).

Usage:
  doc-lint.py --dir <folder>                          lint every set found (any *.behind-the-scenes.md or
                                                      *.technical.md marks one)
  doc-lint.py <guide.md> <behind.md> <technical.md>   lint one explicit set
  --kept-from <git-rev>                               with either form: also report every number and quoted message
                                                      of the guide and Level 2 at that revision that no level holds now

Output: ERROR|WARN <path>:<line> <rule-id> <message>. Exit 0 when no ERROR, 1 otherwise.
Level 3 may be split into <name>.technical.md plus <name>.technical.<topic>.md siblings; Level 3 sections,
row ids, T ids and Q citations are checked over all of them. A set named system-overview has its own sections.

Rules:
  no-sets          ERROR  --dir does not exist or holds no set
  set-complete     ERROR  a set has <name>.md, <name>.behind-the-scenes.md, <name>.technical.md
  levels-links     ERROR  **Levels:** links Guide, Behind the scenes, Technical reference, each to its own
                          level's file (targets exist in --dir mode)
  header           ERROR  **Created:** and either **Owned by:** + **Derived from:** (area) or **Generated by** (feature);
                          Levels 1-2 read them from "## About this document" and an area guide opens that section with
                          **Id:** AREA-nnn; Level 2's **Audience:** is read from the top, under **Levels:**; Level 3
                          reads them all from the top
  audience         ERROR  **Audience:** is shareable (Level 1) / internal (Levels 2-3)
                   WARN   Level 2 marked shareable
  stamp-agree      WARN   a file carries no commit sha, or the three shas differ
  tier-tags        ERROR  #observed / #inferred appear only in Level 3
  confirmed        ERROR  #confirmed in Levels 1-2
                   WARN   #confirmed in Level 3 outside the "How to read this" legend
  code-nouns       ERROR  status codes, HTTP verb + path, source-file names, file:line, inline code in Levels 1-2
                   WARN   code identifiers (PascalCase, lowerCamel, I-prefixed, snake_case) or a bare 4xx/5xx
                          next to a response word in Levels 1-2
                          Inside a ```mermaid fence only the quoted labels and the text after a ":" are read
  jargon           ERROR  technical jargon in Levels 1-2 (Level 2 allows "database"); a mermaid fence as for code-nouns
  defect-words     WARN   bug, defect, flaw, broken, wrong, mistake, faulty, incorrect, vulnerab*, "should have"
                          in Levels 1-2, outside quotes
  guarantee-words  WARN   timing or delivery guarantees in Levels 1-2, outside quotes
  qid-unique       ERROR  Q ids unique across Levels 1-2 open questions; T ids unique in Level 3
  ref-resolves     ERROR  ids cited in the evidence index are Level 3 row ids; Q ids in Level 3 tables exist in
                          Levels 1-2
  index-level      ERROR  every evidence-index Level cell is Guide or Behind the scenes
  index-evidence   ERROR  an #inferred row names a Q or T id; an #observed row has evidence
  index-coverage   ERROR  every flow of Levels 1-2 has an evidence-index row for its heading
  index-steps      WARN   a cited step or outcome number exists in that flow
  sections         ERROR  each level has its required ## headings (Levels 1-2: at least one "For ..." and About this
                          document; Level 1 also Who uses it, Open questions); Evidence index is in the main Level 3 file
  internal-ids     ERROR  Levels 1-2 of an area: an AREA-/FLOW-/ENT-/DEC-/EVT-/RX-/INV- id outside "## About this
                          document", or a Q<n> outside the first cell of an open-questions row
  alerts           ERROR  Levels 1-2: a "> [!X]" alert whose kind is not NOTE, TIP, IMPORTANT or WARNING
  example          WARN   a Level 1 task with a formula line and no **Example**, in a guide with no "A ... in numbers"
  flow-mirror      ERROR  Level 2's "For ..." / "What happens automatically" sections and their ### headings are Level 1's,
                          none added and none out of order; a Level 1 task may be absent
  task-unique      ERROR  two ### task headings with the same text in one Level 1 or Level 2 file
  length           ERROR  words outside fenced blocks, header lines and "## About this document", table cells included:
                          Level 1 > 2,500; Level 2 > 3,000; Level 3 > 4,000 per file, "## Evidence index" not counted
  limits           WARN   Level 1 area guide: a task with more than 7 steps, 5 outcomes or 1 alert; more than 6 key ideas;
                          more than 6 "Good to know" entries
  long-sentence    WARN   Level 1 area guide: a sentence over 30 words, outside tables, fenced blocks and formula lines
  labels           ERROR  Level 1 area guide: a bold span in a **Where:** line or in a person's numbered step that is
                          not a phrase of the first column of Level 3's "Business ↔ code vocabulary"
  diagram          ERROR  Level 1: more than one mermaid fence; a first line other than "stateDiagram-v2" or
                          "flowchart LR"; a flowchart node label not in double quotes
  guarantee-words  also WARN on roadmap promises: a line starting "Not yet", "coming soon", "not yet available /
                          supported / possible", "in a future version / release"
  old-shape        WARN   a set whose guide has "## How it works" (overview: "## The areas") and no "## Who uses it": one
                          WARN for the set and no other check runs on it, so a half-updated KB lints green
  index-line       ERROR  --dir mode with <dir>/INDEX.md: every set under areas/ that is not old-shape has exactly one
                          line "- [Name](areas/x.md) — AREA-nnn · who · what (at most 20 words) · [behind the scenes](..) ·
                          [technical](..) · @ `sha`", and its three links resolve
  fact-kept        WARN   only with --kept-from: a number (not part of an id) or a quoted message that the guide or Level 2
                          held at that revision and that appears nowhere in the set's three levels now
Flows are the ### headings under "## For ..." and "## What happens automatically" (Levels 1-2) or "## End-to-end
flows" (overview). A flow's numbered items are its steps; the bullets under **What happens next** are its outcomes.
"""
