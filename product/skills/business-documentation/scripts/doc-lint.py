#!/usr/bin/env python3
"""Deterministic lint for documentation guides: one guide per area or feature, screenshots beside it.

Usage:
  doc-lint.py --dir <folder>        lint every guide under the folder (a .md file with "## About this document",
                                    or an old three-level guide with a **Levels:** line), and every delivery note
  doc-lint.py <guide.md>...         lint the named guides
  --kept-from <git-rev>             with either form: also report every number and quoted message each guide held
                                    at that revision and holds no longer

Output: ERROR|WARN <path>:<line> <rule-id> <message>. Exit 0 when no ERROR, 1 otherwise.
A guide named system-overview.md has its own sections. A file whose first line starts "# What was delivered" is a
delivery note (docs/deliveries/<NNN>-<plan>.md) and gets only the delivery rules below.

Guide rules:
  no-guides        ERROR  --dir does not exist or holds no guide
  header           ERROR  **Created:** is missing, read from the top or from "## About this document"
  stamp            ERROR  the last-line comment "<!-- guide · key: value · … -->" is missing, or lacks "source: <agent> @
                          <sha>" or "audience: shareable", or (area guide: not the overview, not feature-documenter)
                          "id: AREA-nnn". A guide with the old visible lines and no stamp comment is read from them.
  about-shape      WARN   an old visible line (**Id:**, **Owned by:**, **Derived from:**, **Generated by**, **Models:**,
                          **Audience:**): move it into the stamp comment
  tier-tags        ERROR  #observed / #inferred in a guide
  confirmed        ERROR  #confirmed in a guide
  code-nouns       ERROR  status codes, HTTP verb + path, source-file names, file:line, inline code
                   WARN   code identifiers (PascalCase, lowerCamel, I-prefixed, snake_case) or a bare 4xx/5xx next to a
                          response word; a word inside a bold screen label is the client's own and passes.
                          Inside a ```mermaid fence only the quoted labels and the text after a ":" are read
  jargon           ERROR  technical jargon, unless the product shows the word in a bold label
  defect-words     WARN   bug, defect, flaw, broken, wrong, mistake, faulty, incorrect, vulnerab*, "should have", outside quotes
  guarantee-words  WARN   timing or delivery guarantees outside quotes; roadmap promises ("Not yet", "coming soon",
                          "not yet available / supported / possible", "in a future version / release")
  qid-unique       ERROR  Q ids unique in the open-questions table
  questions        ERROR  the open-questions table header has no Answer column
  sections         ERROR  the required ## headings (In short, Who uses it, Open questions, About this document, at least
                          one "For ..."; the overview has its own list, which also starts with In short)
  in-short         ERROR  "## In short" holds no bullet
                   WARN   more than 5 bullets
  rules            WARN   no "## Rules and limits"; or its table header lacks "Where you meet it"
  formula-place    WARN   a formula line in a task under "## For ..." before that task's **Example** marker
  example          WARN   a guide with "## How it is calculated", no **Example** in any task and no "A ... in numbers"
  automatic        ERROR  a ### under "## What happens automatically" without a **When:** line
                   WARN   one with a **Trigger:** or **Result:** line (old shape)
  renamed-section  WARN   a "## Related areas" heading; it is "## See also"
  internal-ids     ERROR  area and feature guides: an AREA-/FLOW-/ENT-/DEC-/EVT-/RX-/INV-/US id, or a Q<n> outside the
                          first cell of an open-questions row, anywhere but the stamp comment
  alerts           ERROR  a "> [!X]" alert whose kind is not NOTE, TIP, IMPORTANT or WARNING
  task-unique      ERROR  two ### task headings with the same text
  length           ERROR  over 2,500 words outside fenced blocks, header lines and "## About this document"
  limits           WARN   area and feature guides: a task with more than 7 steps, 5 outcomes (bullets under **What happens
                          next** or **What people notice**) or 1 alert; more than 6 key ideas; more than 6 "Good to know"
                          entries; more than 6 "See also" entries
  long-sentence    WARN   area and feature guides: a sentence over 30 words, outside tables, fenced blocks and formulas
  diagram          ERROR  more than one mermaid fence; a first line other than "stateDiagram-v2" or "flowchart LR";
                          a flowchart node label not in double quotes
  screenshots      ERROR  an image outside a person's task (a ### under "## For ..."), in a task with no **Where:**
                          line, a second image in one task, an empty alt text, a file that is not .png/.jpg/.jpeg/.webp,
                          a file that does not exist beside the guide, the same file twice; a guide whose tasks have
                          a **Where:** line and that holds no screenshot, unless About says "**Screenshots:** waived"
                          or "**Screenshots:** pending"
                   WARN   more than 6 screenshots in one guide
  screenshots-pending WARN About says "**Screenshots:** pending": the guide is not finished
  old-shape        WARN   a guide with "## How it works" (overview: "## The areas") and no "## Who uses it": one WARN
                          and no other check runs on it
  retired-level    WARN   --dir mode: a <name>.behind-the-scenes.md or <name>.technical*.md file; any mode: a guide
                          that still carries a **Levels:** line
  index-line       ERROR  --dir mode with <dir>/INDEX.md: every guide under areas/ that is not old-shape has exactly one
                          line "- [Name](areas/x.md) — AREA-nnn · who · what (at most 20 words) · @ `sha`"
  fact-kept        WARN   only with --kept-from: a number (not part of an id) or a quoted message the guide held at that
                          revision and holds no longer

Delivery note rules (no other rule runs; US<n> is the product owner's own id there):
  sections         ERROR  "## Not delivered" or "## About this document" missing
  stamp            ERROR  the last-line comment "<!-- delivery · key: value · … -->" is missing, or lacks "plan:",
                          "source: <agent> @ <sha>" or "audience: shareable"
  tier-tags, confirmed, code-nouns, jargon, defect-words, guarantee-words, long-sentence   as for guides

Tasks are the ### headings under "## For ..." and "## What happens automatically" ("## End-to-end flows" in the
overview). A task's numbered items are its steps.
"""
