class DocLintTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.folder = Path(self.tmp.name).resolve()

    def write(self, name, text):
        path = self.folder / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def screenshots(self, *names):
        target = self.folder / "screenshots"
        target.mkdir(exist_ok=True)
        for name in names:
            (target / name).write_bytes(PNG_BYTES)

    def lint(self, text, name="a.md", kept_from=None):
        return doc_lint.lint_guide(self.write(name, text), kept_from)

    def rules(self, text, name="a.md"):
        return {(f.severity, f.rule) for f in self.lint(text, name)}

    def messages(self, text, rule, name="a.md"):
        return [f.message for f in self.lint(text, name) if f.rule == rule]

    def messages_kept(self, text):
        return [f.message for f in self.lint(text, kept_from="HEAD") if f.rule == "fact-kept"]

    def run_main(self, *args):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = doc_lint.main([str(a) for a in args])
        return code, out.getvalue(), err.getvalue()

    def run_dir(self, folder=None):
        code, out, _ = self.run_main("--dir", folder or self.folder)
        return code, out

    def write_kb(self, index_lines, guide_text=None, folder="areas"):
        self.write(f"{folder}/a.md", guide_text or guide())
        if index_lines is not None:
            self.write("INDEX.md", "# Business Model\n\n## Areas\n" + "\n".join(index_lines) + "\n")

    def git(self, *args):
        subprocess.run(["git", "-C", str(self.folder), *args], check=True, capture_output=True)

    def commit(self, name, text):
        self.git("init", "-q")
        self.write(name, text)
        self.git("add", "-A")
        self.git("-c", "user.name=Doc Lint", "-c", "user.email=doc-lint@example.com", "-c", "commit.gpgsign=false",
                 "commit", "-q", "--no-verify", "-m", "snapshot")

